// Optional solc-js compilation, without changing the project's locked dependencies.
// SOLC_MODULE=/external/path/to/solc/index.js node scripts/compile-contracts.mjs
import fs from "node:fs";
import path from "node:path";
const { default: solc } = await import(process.env.SOLC_MODULE || "solc");
const names = [
  "contracts/SqueekHatchery.sol",
  "contracts/IHatchVerifier.sol",
  "contracts/ProxyImport.sol",
  "contracts/test/MockHatchVerifier.sol",
  "contracts/test/HatcheryV2.sol",
  "contracts/test/ReceiverProbe.sol",
];
const sources = {};
function add(file) {
  if (sources[file]) return;
  const resolved = file.startsWith("@")
    ? path.join("node_modules", file)
    : file;
  const content = fs.readFileSync(resolved, "utf8");
  sources[file] = { content };
  for (const m of content.matchAll(
    /import\s+(?:[^;]*?from\s+)?["']([^"']+)["']/g,
  )) {
    const dep = m[1].startsWith(".")
      ? path.posix.normalize(path.posix.join(path.posix.dirname(file), m[1]))
      : m[1];
    add(dep);
  }
}
for (const n of names) add(n);
const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "prague",
    outputSelection: {
      "*": {
        "*": [
          "abi",
          "evm.bytecode.object",
          "evm.deployedBytecode.object",
          "storageLayout",
        ],
        "": ["ast"],
      },
    },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for (const e of output.errors || []) console.log(e.formattedMessage);
if ((output.errors || []).some((e) => e.severity === "error")) process.exit(1);
fs.mkdirSync("artifacts/contracts", { recursive: true });
for (const [file, contracts] of Object.entries(output.contracts))
  for (const [name, c] of Object.entries(contracts))
    if (file.startsWith("contracts/") || name === "ERC1967Proxy")
      fs.writeFileSync(
        `artifacts/contracts/${name}.json`,
        JSON.stringify(
          {
            contractName: name,
            sourceName: file,
            compiler: solc.version(),
            abi: c.abi,
            bytecode: "0x" + c.evm.bytecode.object,
            deployedBytecode: "0x" + c.evm.deployedBytecode.object,
            storageLayout: c.storageLayout,
          },
          null,
          2,
        ),
      );
fs.writeFileSync(
  "artifacts/contracts/standard-input.json",
  JSON.stringify(input, null, 2),
);
fs.writeFileSync(
  "artifacts/contracts/compiler.json",
  JSON.stringify(
    {
      version: solc.version(),
      optimizer: { enabled: true, runs: 200 },
      evmVersion: "prague",
      viaIR: false,
      openzeppelin: JSON.parse(
        fs.readFileSync(
          "node_modules/@openzeppelin/contracts/package.json",
          "utf8",
        ),
      ).version,
    },
    null,
    2,
  ),
);
fs.writeFileSync(
  "src/abi.ts",
  "// Generated by scripts/compile-contracts.mjs; full proxy-facing implementation ABI.\nexport const HATCHERY_ABI = " +
    JSON.stringify(
      output.contracts["contracts/SqueekHatchery.sol"].SqueekHatchery.abi,
      null,
      2,
    ) +
    " as const;\n",
);
console.log("Compiled", Object.keys(output.contracts).length, "source units");
